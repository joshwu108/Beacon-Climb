"""Render the Model A model card from committed evidence (BC-0209).

    python -I -m beacon_ml.model_card --out ../docs/model-cards/model-a.md

Every number in the card is read from the JSON reports under docs/evidence/BC-0203 and
docs/evidence/BC-0204 (copied from the gitignored reports/ directory); nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
EVIDENCE = REPO / "docs" / "evidence"


def _load(path: Path) -> dict:
    return json.loads(path.read_text())


def _one(folder: str, prefix: str) -> tuple[Path, dict]:
    matches = sorted((EVIDENCE / folder).glob(f"{prefix}*.json"))
    if len(matches) != 1:
        raise SystemExit(f"expected one {prefix}*.json in {folder}, found {len(matches)}")
    return matches[0], _load(matches[0])


def _ci(values) -> str:
    return f"[{values[0]:.3f}, {values[1]:.3f}]"


def _row(name: str, res: dict) -> str:
    a = res["all"]
    hi3, hi10 = res.get("ascents>=3"), res.get("ascents>=10")
    return (
        f"| {name} | {a['mae']:.3f} {_ci(a['mae_ci95'])} | {a['rmse']:.3f} | {a['bias']:+.3f} | "
        f"{a['v_exact']:.3f} | {a['v_within_1']:.3f} {_ci(a['v_within_1_ci95'])} | "
        f"{hi3['mae']:.3f} (n={hi3['n']}) | {hi10['mae']:.3f} (n={hi10['n']}) |"
    )


HEADER = (
    "| Model | MAE [95% CI] | RMSE | Bias | V exact | V within 1 [95% CI] | "
    "MAE, ascents ≥ 3 | MAE, ascents ≥ 10 |\n|---|---|---|---|---|---|---|---|"
)


def _slice_table(results: dict, model: str, prefix: str, label: str) -> list[str]:
    res = results[model]
    keys = [k for k in res if k.startswith(prefix)]
    if prefix == "angle=":
        keys.sort(key=lambda k: int(k.split("=")[1]))
    else:
        keys.sort(key=lambda k: int(k.removeprefix("true_V")))
    out = [f"| {label} | n | MAE [95% CI] | V within 1 | Bias |", "|---|---|---|---|---|"]
    for k in keys:
        a = res[k]
        out.append(
            f"| {k.split('=')[-1] if prefix == 'angle=' else k.removeprefix('true_')} | "
            f"{a['n']} | {a['mae']:.3f} {_ci(a['mae_ci95'])} | {a['v_within_1']:.3f} | "
            f"{a['bias']:+.3f} |"
        )
    return out


def render() -> str:
    val_path, val = _one("BC-0203", "val-")
    test_path, test = _one("BC-0203", "test-")
    sweep_path, sweep = _one("BC-0204", "val-sweep-")
    ds_test_path, ds_test = _one("BC-0204", "test-")
    rel = lambda p: p.relative_to(REPO).as_posix()

    gbm_name = test["best"]
    ds_res = ds_test["results"]["deepsets"]
    gbm_in_ds = ds_test["results"][gbm_name]
    paired = next(iter(ds_test["paired_differences"].values()))
    ds_better = paired["ci95"][1] < 0
    shipped = "Deep Sets candidate" if ds_better else gbm_name
    hw = test["hardware"]

    lines = [
        "# Model card — Model A (route grade prediction), Kilter layout 1",
        "",
        "**LOCAL RESEARCH ONLY.** Trained on the Hugging Face `Vilin97/KilterBoard` splits under the",
        "owner's local-research sign-off (`docs/data-source-audit.md` section 7). Weights,",
        "embeddings and per-route predictions never leave this machine and are never published;",
        "only the aggregate metrics below may be shared. Generated by `beacon_ml.model_card` from",
        f"`{rel(val_path)}`, `{rel(test_path)}`, `{rel(sweep_path)}` and `{rel(ds_test_path)}`.",
        "",
        "## What it does and what it does not",
        "",
        "Given the holds of a climb on Kilter layout 1 (position, role, which physical hold) and the",
        "wall angle, the model estimates the community consensus grade on Aurora's",
        "`difficulty_numeric` axis (10 ≈ 4a/V0 … 31 ≈ 8b+/V14). It is a statement about how the",
        "Kilter app community graded similar climbs, **not** about how hard a climb is for a",
        "particular person, and not safety, injury or training advice. It knows nothing about other",
        "boards or gym walls.",
        "",
        "## Data",
        "",
        f"- Dataset `{test['dataset_id']}` (`docs/data-cards/model-a-kilter.md`): train "
        f"{test['n_train']} rows, test {test['n_eval']} rows (one row = one climb at one angle).",
        "- Official uuid splits, with climbs whose hold set (or mirror image) appears in an earlier",
        "  split removed from val and test. Labels are community grades; most rows have fewer than",
        "  3 logged ascents, so results are also reported on ascents ≥ 3 and ≥ 10 subsets",
        "  (thresholds fixed before any run).",
        "- Features: `model-a-features-v1` (`docs/ml/model-a-features.md`): 35 geometry/angle",
        "  features, plus hold-identity indicators fitted on train only.",
        "",
        "## Protocol",
        "",
        "1. Every candidate was fitted on train and compared on validation only; the gradient-",
        "   boosting grid and the Deep Sets sweep were declared in the configs before running.",
        "2. The selected candidates were frozen (configs and checkpoint hashes), then the sealed",
        "   test split was opened once per frozen comparison; each opening is logged in",
        "   `docs/evidence/BC-0203/test-access.log`.",
        "3. Intervals are 95% percentile bootstraps (1000 resamples) that resample whole climbs,",
        "   because the angles of one climb are correlated. Paired differences use the same",
        "   resamples for both models.",
        "",
        "## Results on the sealed test split (difficulty units; 1 unit = one Font sub-grade)",
        "",
        HEADER,
    ]
    for name, res in test["results"].items():
        lines.append(_row(name, res))
    lines.append(_row("Deep Sets candidate", ds_res))
    lines += [
        "",
        "Paired differences in MAE (negative = first model better):",
        "",
        "| Comparison | MAE difference [95% CI] |",
        "|---|---|",
    ]
    for k, v in {**test["paired_differences"], **ds_test["paired_differences"]}.items():
        lines.append(f"| {k} | {v['mae_a_minus_b']:+.3f} {_ci(v['ci95'])} |")
    same = abs(gbm_in_ds["all"]["mae"] - test["results"][gbm_name]["all"]["mae"]) < 1e-9
    lines += [
        "",
        "The gradient-boosting model refitted inside the Deep Sets comparison reproduces the",
        f"BC-0203 test MAE {'exactly' if same else 'NOT exactly (see reports)'} "
        f"({gbm_in_ds['all']['mae']:.3f}).",
        "",
        "## Decision",
        "",
        f"**Shipped: {shipped}.** "
        + (
            "The Deep Sets candidate is better than gradient boosting with an interval that "
            "excludes zero."
            if ds_better
            else (
                "The Deep Sets candidate was worse than gradient boosting (paired interval above "
                "zero), "
                if paired["ci95"][0] > 0
                else "The Deep Sets candidate did not beat gradient boosting with an interval below zero, "
            )
            + "so the simpler model ships. The Deep Sets model is kept as the source of 32-d route "
            "embeddings for similarity, where gradient boosting has none."
        ),
        "",
        "## Where it is weaker",
        "",
        *_slice_table(test["results"], gbm_name, "angle=", "Angle"),
        "",
        *_slice_table(test["results"], gbm_name, "true_V", "True grade"),
        "",
        "## Limitations",
        "",
        "- Community grades are noisy and drift; the label itself has error the model cannot remove.",
        "- Predictions shrink toward the middle of the grade range: easy climbs are over-predicted",
        "  and hard ones under-predicted (bias column of the true-grade table). Do not use it to",
        "  rank the hardest climbs; at V10 and above it is right within one V grade less than half",
        "  the time.",
        "- Steep extremes (65° and 70°) and near-vertical angles have the largest errors.",
        "- Rare angles and the hardest grades have few test rows; their intervals are wide.",
        "- Hold identity carries most of the gain over geometry alone. A new or rearranged hold set",
        "  loses that signal (unseen holds contribute nothing).",
        "- One board, one community, one snapshot of the app data; no claim transfers elsewhere.",
        "- The test set was used once per frozen comparison, but it was used; future model changes",
        "  need a new held-out split or a prospective check before any new claim.",
        "",
        "## Reproduce",
        "",
        "```sh",
        "make extract-kilter && make freeze-dataset",
        "make train-model-a-val            # writes reports/model-a/<run>/selection.json",
        "make train-model-a-test SELECTION=reports/model-a/<run>/selection.json",
        "make train-deepsets-val",
        "make train-deepsets-test CANDIDATE=... SELECTION=...",
        "```",
        "",
        f"Hardware: {hw['chip']}, {hw['cpus']} CPUs, {hw['os']}, Python {hw['python']}, "
        f"numpy {hw['numpy']}, scikit-learn {hw['scikit-learn']}"
        + (f", torch {ds_test['hardware'].get('torch')}" if "torch" in ds_test["hardware"] else "")
        + f". Code: commit `{test['git']['commit'][:12]}` (baseline test run).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the Model A model card")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    args.out.write_text(render())
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
