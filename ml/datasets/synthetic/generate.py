# --------------------------------------------------------------------------------------
# RFC 8785 canonical JSON (subset sufficient for catalog records)
# --------------------------------------------------------------------------------------
def _canonical_number(value: float) -> str:
    """ECMAScript Number::toString for the finite, exponent-free values this generator emits."""
    if not math.isfinite(value):
        raise ValueError("non-finite number")
    if value == int(value) and abs(value) < 1e21:
        return str(int(value))  # 1.0 -> "1", 0.0 / -0.0 -> "0"
    text = repr(value)  # shortest round-trip repr, same digits as ES for these magnitudes
    if "e" in text or "E" in text:
        raise ValueError(f"number {text} needs exponent formatting; not supported here")
    return text


def canonical_json(value) -> str:
    """Serialise ``value`` per RFC 8785: sorted keys (UTF-16 code unit order), no whitespace,
    ES number formatting, JSON escapes only for the mandatory characters."""
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return _canonical_number(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        return "[" + ",".join(canonical_json(v) for v in value) + "]"
    if isinstance(value, dict):
        keys = sorted(value, key=lambda k: k.encode("utf-16-be"))
        return (
            "{"
            + ",".join(
                f"{json.dumps(k, ensure_ascii=False)}:{canonical_json(value[k])}" for k in keys
            )
            + "}"
        )
    raise TypeError(f"unsupported type {type(value).__name__}")


def content_sha256(canonical_lines: list[str]) -> str:
    """README rule: sha256 of UTF-8 of the canonical non-manifest lines joined by LF, no trailing LF."""
    return hashlib.sha256("\n".join(canonical_lines).encode("utf-8")).hexdigest()


# --------------------------------------------------------------------------------------
# Board
# --------------------------------------------------------------------------------------
def hold_id(row: int, col: int) -> str:
    return f"h{row * GRID + col + 1:03d}"


def build_board() -> dict:
    holds = []
    for row in range(GRID):
        for col in range(GRID):
            holds.append(
                {
                    "provider_hold_id": hold_id(row, col),
                    "x": round((col + 0.5) / GRID, COORD_DECIMALS),
                    "y": round((row + 0.5) / GRID, COORD_DECIMALS),
                    "geometry_meta": {"row": row, "col": col},
                }
            )
    return {
        "type": "board",
        "board_id": BOARD_ID,
        "provider": SOURCE,
        "layout_id": LAYOUT_ID,
        "size_id": SIZE_ID,
        "synthetic": True,
        "geometry": {"units": "NORMALIZED", "width": 1.0, "height": 1.0, "y_axis": "UP"},
        "available_angles": list(AVAILABLE_ANGLES),
        "holds": holds,
    }


# --------------------------------------------------------------------------------------
# Routes
# --------------------------------------------------------------------------------------
def toy_grade(rng: random.Random, rows: list[int], hand_count: int, angle_deg: int) -> float:
    """TOY grade. grade = 10 + 0.6 * vertical_span_cells + 0.9 * max(0, 8 - hand_count)
    + angle_deg / 10 + N(0, 1), clipped to [10, 33], rounded to 1 decimal.
    Not a difficulty model; see the module docstring."""
    span = max(rows) - min(rows)
    missing_hands = max(0, HAND_HOLDS_REFERENCE - hand_count)
    raw = (
        GRADE_BASE
        + GRADE_PER_SPAN_CELL * span
        + GRADE_PER_MISSING_HAND * missing_hands
        + GRADE_PER_ANGLE_DEG * angle_deg
        + rng.gauss(0.0, GRADE_NOISE_SD)
    )
    return round(min(GRADE_MAX, max(GRADE_MIN, raw)), GRADE_DECIMALS)


def observation_count(rng: random.Random) -> int:
    return min(OBSERVATION_MAX, int(rng.expovariate(1.0 / OBSERVATION_MEAN)))


def _pick_cells(
    rng: random.Random, rows: list[int], count: int, taken: set[tuple[int, int]]
) -> list[tuple[int, int]]:
    """Pick ``count`` distinct free cells whose row is drawn from ``rows``."""
    free = [(r, c) for r in rows for c in range(GRID) if (r, c) not in taken]
    cells = rng.sample(free, count)
    taken.update(cells)
    return cells


def build_placements(rng: random.Random) -> list[dict]:
    total = rng.randint(MIN_PLACEMENTS, MAX_PLACEMENTS)
    start_count = rng.randint(1, 2)
    finish_count = 1 if total - start_count < 4 else rng.randint(1, 2)
    remaining = total - start_count - finish_count
    foot_count = rng.randint(0, min(MAX_FOOT_HOLDS, max(0, remaining - 1)))
    hand_count = remaining - foot_count

    taken: set[tuple[int, int]] = set()
    starts = _pick_cells(rng, list(START_ROWS), start_count, taken)
    middle_rows = list(range(START_ROWS[-1] + 1, FINISH_ROW))
    hands = sorted(_pick_cells(rng, middle_rows, hand_count, taken))
    finishes = _pick_cells(rng, [FINISH_ROW], finish_count, taken)
    foot_rows = list(range(GRID // 2))
    feet = sorted(_pick_cells(rng, foot_rows, foot_count, taken))

    ordered = [(c, "START") for c in starts] + [(c, "HAND") for c in hands]
    ordered += [(c, "FINISH") for c in finishes] + [(c, "FOOT") for c in feet]
    return [
        {"provider_hold_id": hold_id(r, c), "role": role, "placement_order": i}
        for i, ((r, c), role) in enumerate(ordered)
    ]


def build_variants(rng: random.Random, placements: list[dict]) -> list[dict]:
    rows = [int(p["provider_hold_id"][1:]) - 1 for p in placements]
    rows = [idx // GRID for idx in rows]
    hand_count = sum(1 for p in placements if p["role"] == "HAND")
    angles = sorted(rng.sample(AVAILABLE_ANGLES, rng.randint(1, MAX_VARIANTS)))
    variants = []
    for angle in angles:
        grade = toy_grade(rng, rows, hand_count, angle)
        status = "RETIRED" if rng.random() < RETIRED_FRACTION else "ACTIVE"
        if rng.random() < UNGRADED_FRACTION:
            variants.append(
                {
                    "angle_deg": angle,
                    "grade_numeric": None,
                    "grade_observation_count": 0,
                    "validation_status": status,
                }
            )
            continue
        variants.append(
            {
                "angle_deg": angle,
                "grade_numeric": grade,
                "grade_observation_count": max(1, observation_count(rng)),
                "validation_status": status,
            }
        )
    return variants


def build_route(rng: random.Random, index: int) -> dict:
    placements = build_placements(rng)
    variants = build_variants(rng, placements)
    setter = None if rng.random() < NULL_SETTER_FRACTION else rng.choice(SETTER_PSEUDONYMS)
    tags = sorted(rng.sample(TAGS, rng.randint(0, MAX_TAGS)))
    active_from = f"2026-{rng.randint(1, 9):02d}-{rng.randint(1, 28):02d}T00:00:00Z"
    return {
        "type": "route",
        "provider_route_uuid": f"syn-route-{index:04d}",
        "board_id": BOARD_ID,
        "name": f"{rng.choice(NAME_ADJECTIVES)} {rng.choice(NAME_NOUNS)}",
        "setter_pseudonym": setter,
        "tags": tags,
        "active_from": active_from,
        "active_to": None,
        "placements": placements,
        "variants": variants,
    }


# --------------------------------------------------------------------------------------
# File
# --------------------------------------------------------------------------------------
def build_records(seed: int, routes: int) -> list[dict]:
    """Return [board, route_1, ..., route_n] for ``seed``; the manifest is added by ``render``."""
    if routes < 1:
        raise ValueError("--routes must be >= 1")
    rng = random.Random(seed)
    records = [build_board()]
    records.extend(build_route(rng, i) for i in range(1, routes + 1))
    return records


def build_manifest(canonical_lines: list[str], boards: int, routes: int) -> dict:
    return {
        "type": "manifest",
        "schema_version": SCHEMA_VERSION,
        "source": SOURCE,
        "version": VERSION,
        "content_sha256": content_sha256(canonical_lines),
        "extracted_at": EXTRACTED_AT,
        "synthetic": True,
        "license_review_status": "SYNTHETIC",
        "record_counts": {"boards": boards, "routes": routes},
        "notes": NOTES,
    }


def render(seed: int, routes: int) -> bytes:
    """Full file bytes: manifest line, board line, route lines, each LF-terminated."""
    records = build_records(seed, routes)
    canonical_lines = [canonical_json(r) for r in records]
    boards = sum(1 for r in records if r["type"] == "board")
    manifest = build_manifest(canonical_lines, boards, len(records) - boards)
    lines = [canonical_json(manifest)] + canonical_lines
    return ("\n".join(lines) + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="SYNTHETIC demo board -> catalog v1 JSON Lines.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--routes", type=int, default=300)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    data = render(args.seed, args.routes)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(data)
    print(
        f"wrote {args.out} ({len(data)} bytes, seed={args.seed}, routes={args.routes}) [SYNTHETIC]"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
