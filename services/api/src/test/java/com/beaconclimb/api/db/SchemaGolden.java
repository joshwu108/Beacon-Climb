package com.beaconclimb.api.db;

import com.beaconclimb.api.AbstractPostgresIT;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.stream.Collectors;
import org.testcontainers.containers.Container.ExecResult;
import org.testcontainers.postgresql.PostgreSQLContainer;

/**
 * Produces the golden schema document docs/db/schema-v1.md from a pg_dump taken inside the test
 * container, and reads the fenced SQL block back for comparison. Normalisation strips everything
 * that is environment-specific (comments, SET lines, psql meta-commands such as the random {@code
 * \restrict} key newer pg_dump versions emit) and the Flyway bookkeeping table.
 */
final class SchemaGolden {

  static final String UPDATE_ENV_VAR = "UPDATE_SCHEMA_DOC";
  static final Path DOC_PATH =
      Path.of("..", "..", "docs", "db", "schema-v1.md").toAbsolutePath().normalize();
  private static final String FENCE = "```sql\n";
  private static final String FENCE_END = "\n```";
  private static final String HEADER =
      """
      # Beacon Climb database schema, V1

      Generated by `MigrationIT` (`services/api/src/test/java/com/beaconclimb/api/db`) from
      `pg_dump --schema-only --no-owner --no-privileges` of every Flyway migration under
      `services/api/src/main/resources/db/migration` (currently `V1__identity_catalog_provenance.sql`
      and `V2__sessions.sql`) applied to Postgres 17 in Testcontainers. Do not edit by hand.
      Regenerate with `UPDATE_SCHEMA_DOC=1 ./gradlew :api:test --tests '*MigrationIT*'`; the same
      test fails when this file drifts from the live schema. Tables: PRD 6.1, ADR-0002, ADR-0005.

      """;

  private SchemaGolden() {}

  static boolean shouldUpdate() {
    return "1".equals(System.getenv(UPDATE_ENV_VAR));
  }

  /**
   * The shared container is the public singleton in {@link AbstractPostgresIT}; this helper lives
   * in a subpackage and is the only pg_dump client.
   */
  static PostgreSQLContainer sharedContainer() {
    return AbstractPostgresIT.POSTGRES;
  }

  static String dumpNormalisedSchema(PostgreSQLContainer postgres)
      throws IOException, InterruptedException {
    ExecResult result =
        postgres.execInContainer(
            "sh",
            "-c",
            "PGPASSWORD='"
                + postgres.getPassword()
                + "' pg_dump --schema-only --no-owner --no-privileges -U "
                + postgres.getUsername()
                + " -d "
                + postgres.getDatabaseName());
    if (result.getExitCode() != 0) {
      throw new IOException("pg_dump failed: " + result.getStderr());
    }
    return normalise(result.getStdout());
  }

  static String normalise(String dump) {
    String withoutNoise =
        Arrays.stream(dump.split("\n"))
            .filter(line -> !isNoise(line))
            .collect(Collectors.joining("\n"));
    return Arrays.stream(withoutNoise.split(";\n"))
        .map(String::strip)
        .map(
            statement ->
                statement.endsWith(";")
                    ? statement.substring(0, statement.length() - 1)
                    : statement)
        .filter(statement -> !statement.isEmpty())
        .filter(statement -> !statement.contains("flyway_schema_history"))
        .map(statement -> statement + ";")
        .collect(Collectors.joining("\n\n"));
  }

  private static boolean isNoise(String line) {
    return line.isBlank()
        || line.startsWith("--")
        || line.startsWith("SET ")
        || line.startsWith("SELECT pg_catalog.set_config")
        || line.startsWith("\\");
  }

  static void writeDoc(String normalisedSchema) throws IOException {
    Files.createDirectories(DOC_PATH.getParent());
    Files.writeString(
        DOC_PATH, HEADER + FENCE + normalisedSchema + FENCE_END + "\n", StandardCharsets.UTF_8);
  }

  static String readDocSql() throws IOException {
    String doc = Files.readString(DOC_PATH, StandardCharsets.UTF_8);
    int start = doc.indexOf(FENCE);
    int end = doc.lastIndexOf(FENCE_END);
    if (start < 0 || end < start) {
      throw new IOException("No fenced sql block in " + DOC_PATH);
    }
    return doc.substring(start + FENCE.length(), end);
  }
}
